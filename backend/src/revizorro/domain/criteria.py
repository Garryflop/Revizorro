from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

IndividualCriterion = Literal[
    "necessary",
    "appropriate",
    "unambiguous",
    "complete",
    "singular",
    "feasible",
    "verifiable",
    "correct",
    "conforming",
]

SetCriterion = Literal[
    "set_complete",
    "set_consistent",
    "set_feasible",
    "set_comprehensible",
    "set_validatable",
    "ranked",
    "modifiable",
    "traceable",
]

Criterion = IndividualCriterion | SetCriterion


@dataclass(frozen=True)
class CriterionInfo:
    code: str
    name: str
    source: str
    violation: str  # what a violation looks like; used verbatim in prompts


