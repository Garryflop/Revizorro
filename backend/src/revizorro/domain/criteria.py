ALL: dict[str, CriterionInfo] = {**INDIVIDUAL, **SET}


def criteria_prompt_block(catalog: dict[str, CriterionInfo]) -> str:
    """Render criteria as a list for system prompts."""
    return "\n".join(
        f"- `{c.code}` — {c.name} ({c.source}). Нарушение: {c.violation}." for c in catalog.values()
    )
